/**
 * 从 Markdown 文件名推导 Astro 生成的文章路径。
 *
 * 为什么要有这个模块：**路径是 Astro 生成的，但清单是构建脚本自己拼的**。
 * 两套规则一旦不一致，页面本身是好的、清单里的链接却全是 404 ——
 * 私人角落和手机写作页点开都打不开，而且很难想到原因。
 *
 * 踩过的实例：
 *   文件 2026-09-18-SEP.-26.md  →  Astro 输出 /posts/2026-09-18-sep-26/
 *   而脚本按文件名拼成      /posts/2026-09-18-SEP.-26/  → 404
 *
 * Astro 的规则（**标点是删掉，不是换成 -**）：
 *   小写 → 空白变 - → 其余非 [a-z0-9\u4e00-\u9fa5_-] 的字符【直接删掉】
 *   → 合并连续 - → 去掉首尾 -。中文原样保留
 *   （站点里本来就有 2026-09-16-yuuu的第一篇文章 这种）。
 *
 * ⚠️ 这条规则我搞错过一次，代价是一篇文章的公开发链接 404：
 *   文件 2026-09-20-恭喜自己，终于脱贫啦！.md
 *     Astro 输出 /posts/2026-09-20-恭喜自己终于脱贫啦/   ← 标点被删掉
 *     我拼成   /posts/2026-09-20-恭喜自己-终于脱贫啦/   ← 标点被换成 -
 *   而早先拿 2026-09-18-SEP.-26 对账时**恰好两者结果相同**
 *   （那个 . 后面本来就跟着 -），所以没发现。
 *   教训：对账不能挑样本，要**把全部文章都比一遍**。
 *   tools/audit-dist.mjs 现在就把「全部文件名 slugify」和「全部产物目录」
 *   做集合比较，任何一篇对不上都会直接报错。
 */

/** 文件名（带不带 .md 都行）→ Astro 的 slug */
export function slugify(name: string): string {
  return String(name)
    .replace(/\.md$/, '')
    .toLowerCase()
    .replace(/\s+/g, '-')
    .replace(/[^a-z0-9\u4e00-\u9fa5_-]+/g, '')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
}

/** 文章在站点上的路径：/posts/<slug>/ */
export const postUrl = (name: string): string => '/posts/' + slugify(name) + '/';
